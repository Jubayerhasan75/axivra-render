def esc(s):
    return html.escape(str(s or ""), quote=True)


def clean_md(t):
    return re.sub(r"\*{1,2}([^*]+)\*{1,2}", r"[[\1]]", str(t or "")).replace("*", "").strip()


def sub_html(text):
    text = clean_md(text)
    if not text:
        return ""
    out, pos = [], 0
    for m in re.finditer(r"\[\[(.+?)\]\]", text):
        out.append(esc(text[pos:m.start()])); out.append("<b>%s</b>" % esc(m.group(1))); pos = m.end()
    out.append(esc(text[pos:]))
    return "".join(out)


def headline_html(text, upper):
    text = clean_md(text)
    if "[[" not in text:
        words = text.split()
        cut = max(1, (len(words) + 1) // 2)
        text = " ".join(words[:cut]) + " [[" + " ".join(words[cut:]) + "]]"
    out, pos = [], 0
    for m in re.finditer(r"\[\[(.+?)\]\]", text):
        out.append(esc(text[pos:m.start()]))
        out.append('<span class="hl">%s</span>' % esc(m.group(1)))
        pos = m.end()
    out.append(esc(text[pos:]))
    return "".join(out)


